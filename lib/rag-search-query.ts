/**
 * Единый промпт для LLM: из диалога + фокуса сформировать ОДНУ строку гибридного запроса к RAG.
 * Протокол обследования — фиксированные 10 разделов по порядку; запрос должен отражать текущий этап.
 */

const HIDDEN_BLOCK_RE = /<AI-HIDDEN>[\s\S]*?<\/AI-HIDDEN>/gi;

/**
 * Убирает служебные вставки (плейсхолдеры вложений, [RAG], скрытые блоки), чтобы запрос к индексу
 * не содержал текста вроде «[Вложение … только имя]» — иначе LightRAG даёт пустые keywords и плохой retrieval.
 */
export function stripTextForRagQuery(input: string): string {
  let s = String(input ?? "");
  s = s.replace(HIDDEN_BLOCK_RE, " ");
  s = s.replace(/\[RAG\][^\n]*/gi, " ");
  s = s.replace(/\[Вложение «[^»]+»[^\]]*\]/g, " ");
  s = s.replace(/\[Файл «[^»]+»[^\]]*\]/g, " ");
  s = s.replace(/полный текст в промпт[^\n.]*/gi, " ");
  s = s.replace(/только имя[^\n.;]*/gi, " ");
  s = s.replace(/включён контекст из RAG[^\n.]*/gi, " ");
  s = s.replace(/\s+/g, " ").trim();
  return s;
}

export const RAG_PROTOCOL_TEN_SECTIONS_RU = `
Фиксированная структура протокола обследования (10 разделов, порядок не меняется):
1. Номер протокола и дата встречи
2. Повестка встречи (тема, пункты)
3. Участники — заказчик и исполнитель (организации, ФИО, должности)
4. Термины и определения
5. Сокращения и обозначения
6. Содержание встречи (ход обсуждения, темы)
7. Вопросы и ответы
8. Решения (с указанием ответственных)
9. Открытые вопросы
10. Утверждение (подписи сторон)
`.trim();

/** Транскрипт последних реплик из сообщений чата (до convertToModelMessages). */
export function hydratedChatTranscriptForRag(messages: unknown[], maxChars: number): string {
  const tail = Array.isArray(messages) ? messages.slice(-24) : [];
  const lines: string[] = [];
  for (const m of tail) {
    const rec = m as { role?: string; content?: string };
    const role =
      rec.role === "assistant" ? "assistant" : rec.role === "user" ? "user" : null;
    if (!role) continue;
    const raw = typeof rec.content === "string" ? rec.content : "";
    const t = stripTextForRagQuery(raw.replace(/\s+/g, " ").trim());
    if (!t) continue;
    lines.push(`${role}: ${t}`);
  }
  const joined = lines.join("\n");
  if (joined.length <= maxChars) return joined;
  return joined.slice(joined.length - maxChars);
}

export function buildRagHybridQueryPrompt(transcript: string, purposeFocus: string): string {
  return `Ты формулируешь ОДИН поисковый запрос для гибридного поиска (семантика + ключевые слова) по корпоративным документам.

${RAG_PROTOCOL_TEN_SECTIONS_RU}

КАК ОПРЕДЕЛИТЬ ЭТАП (раздел 1–10):
- Прочитай диалог с конца: последний вопрос пользователя и твоя предыдущая реплика (уточняющий вопрос обычно намекает на раздел).
- Если ассистент спрашивает про номер/дату — ориентир раздел 1; повестку — 2; состав участников — 3; термины — 4; сокращения — 5; пересказ обсуждения — 6; Q&A — 7; решения и ответственных — 8; нерешённое — 9; подписи — 10.
- Если пользователь явно назвал раздел или тему («термины», «решения», «кто подписывает») — используй это.
- Если этап неочевиден, выбери наиболее вероятный раздел по смыслу последней реплики пользователя и добавь в запрос ключевые слова этого раздела.
- Не добавляй «раздел N» в запрос искусственно, если вопрос пользователя общий и не про оформление протокола — тогда достаточно сущностей из диалога + «протокол обследования шаблон Форус».

ЧТО ДОЛЖЕН СОДЕРЖАТЬ ЗАПРОС:
- Явно или через синонимы: тематику раздела (например «решения ответственный»).
- Конкретику из диалога: названия систем/продуктов, даты, номера, ФИО, организации — если помогают найти релевантный фрагмент в базе.
- Не копируй длинные цитаты расшифровки целиком — только сущности и формулировки для поиска.
- **Запрещено** включать в строку запроса: подстроки вида «[Вложение …]», «[RAG]», «только имя», «полный текст в промпт» — это служебный мусор, не ключевые слова для поиска в базе.

Фрагмент диалога (user = пользователь, assistant = ассистент):
"""
${stripTextForRagQuery(transcript)}
"""

Фокус от ассистента (цель поиска; может быть кратким): ${purposeFocus}

ПРАВИЛА ВЫВОДА:
- Выведи ТОЛЬКО текст запроса одной строкой, без кавычек, префиксов и пояснений.
- Длина не более 600 символов.
- Язык: русский (редкие английские аббревиатуры из диалога допустимы).`;
}
