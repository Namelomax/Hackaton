import { tool } from 'ai';
import { z } from 'zod';
import { addGlossaryRule, listGlossaryEntries } from '@/lib/prompts/glossary';

/**
 * Инструмент чат-агента: добавить правило замены в глоссарий (data/glossary.md).
 * Вызывается, когда пользователь просит не употреблять слово/формулировку в
 * протоколе («не пиши "сделать", пиши "выполнить"»). Правило действует сразу:
 * попадает в контекст генерации и в детерминированную подстановку перед выводом.
 */
export function createAddGlossaryRuleTool() {
  return tool({
    description:
      'Добавить постоянное правило замены слова/словосочетания для текста протокола. ' +
      'Вызывай, когда пользователь просит НЕ использовать какое-то слово или выражение в документе ' +
      'и/или указывает, чем его заменять (например: «не пиши "погнали", пиши "приступили"», ' +
      '«убери слово "коллеги" из протоколов»). Правило сохраняется навсегда и действует во всех будущих документах. ' +
      'НЕ вызывай для разовых правок конкретного места в текущем документе.',
    inputSchema: z.object({
      from: z
        .string()
        .min(1)
        .max(100)
        .describe('Слово или словосочетание, которое запрещено использовать (как его пишут в тексте).'),
      to: z
        .string()
        .max(200)
        .describe('Замена в официально-деловом стиле. Пустая строка — слово просто удаляется.'),
    }),
    execute: async ({ from, to }) => {
      const entries = addGlossaryRule(from, to);
      return {
        ok: true as const,
        saved: { from, to },
        totalRules: entries.length,
      };
    },
  });
}

/** Текущий список правил (может пригодиться агенту для ответа пользователю). */
export function glossarySummaryLine(): string {
  const entries = listGlossaryEntries();
  return `Правил в глоссарии: ${entries.length}.`;
}
