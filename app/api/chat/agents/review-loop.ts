/**
 * Само-ревью готового протокола ЛОКАЛЬНОЙ моделью.
 *
 * Заменяет прежнюю точечную пост-проверку падежей: вместо узкого прохода
 * «только падежи подставленных значений» модель получает ВЕСЬ готовый
 * протокол и задачу пользователя и правит только ФАКТИЧЕСКИЕ ошибки —
 * неприменённую правку, рассогласованный падеж подстановки, оставшийся
 * плейсхолдер, дословную стенограмму вместо связного текста, инфинитивы
 * вместо будущего времени в «Решили». Логику решений не оценивает и
 * ничего не выдумывает.
 *
 * Модель — ВСЕГДА локальная (данные уже деанонимизированы, в облако их
 * отправлять нельзя). Любая ошибка — LLM недоступна, невалидный JSON,
 * протокол не прошёл схему — не должна портить уже собранный документ:
 * функция тихо возвращает исходный protocol без изменений.
 */

import { generateObject } from 'ai';
import {
  ProtocolSchema,
  parseProtocolStrict,
  coerceProtocolPartial,
  type Protocol,
} from '@/lib/schemas/protocol-schema';

const REVIEW_PROMPT = `Ты — контролёр качества протокола. Тебе дан ГОТОВЫЙ протокол (JSON) и ЗАДАЧА пользователя. Проверь ТОЛЬКО ФАКТИЧЕСКИЕ ошибки и верни исправленный протокол тем же JSON по схеме.

Что считать фактической ошибкой:
1. Правка из задачи пользователя НЕ применена (например, просили изменить должность/значение, а в документе старое или «требует уточнения»).
2. Грамматика/падеж подставленных имён и организаций не согласуется с фразой («подключением Чайка» → «подключением Чайки»).
3. В тексте остался плейсхолдер вида [PERSON_1]/[ORG_1].
4. Стенограмма — дословный пересказ реплик вместо связного делового текста в «Обсудили».
5. Инфинитивы вместо будущего времени в «Решили» («завершить» → «завершит»).

ЗАПРЕЩЕНО: оценивать логику/осмысленность решений; добавлять или выдумывать факты, числа, даты, сроки, ФИО, которых нет во входных данных; менять значения, которые и так верны; переписывать стиль сверх перечисленного.

Если фактических ошибок нет — верни протокол БЕЗ ИЗМЕНЕНИЙ. Ответ — только JSON по схеме.

ЗАДАЧА ПОЛЬЗОВАТЕЛЯ:
{{REQUEST}}

ПРОТОКОЛ (JSON):
{{DOCUMENT}}`;

export type ReviewAndCorrectOptions = {
  /** Готовый протокол с РЕАЛЬНЫМИ данными (после деанонимизации). */
  protocol: Protocol;
  /** Задача/правки пользователя (последние сообщения). */
  userRequest: string;
  /** ЛОКАЛЬНАЯ модель. */
  model: any;
  abortSignal?: AbortSignal;
};

/**
 * Прогоняет протокол через локальную модель-контролёра и возвращает
 * исправленную версию. При любой ошибке — возвращает исходный protocol.
 */
export async function reviewAndCorrectProtocol(
  options: ReviewAndCorrectOptions,
): Promise<Protocol> {
  const { protocol, userRequest, model, abortSignal } = options;

  try {
    const documentJson = JSON.stringify(protocol);
    const prompt = REVIEW_PROMPT.replace('{{REQUEST}}', userRequest ?? '').replace(
      '{{DOCUMENT}}',
      documentJson,
    );

    const result = await generateObject({
      model,
      schema: ProtocolSchema,
      prompt,
      temperature: 0,
      maxOutputTokens: 8192,
      ...(abortSignal ? { abortSignal } : {}),
    });

    return parseProtocolStrict(coerceProtocolPartial(result.object));
  } catch (e) {
    console.warn('[review-loop] пропущено:', (e as Error)?.message ?? e);
    return protocol;
  }
}
